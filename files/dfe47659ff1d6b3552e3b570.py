# Python: множества, добавление обязательных элементов

p = {1, 2, 3, 5, 7, 10, 11, 15, 17, 25}
q = {2, 3, 4, 5, 6, 7, 8, 12, 15, 25}
a = set()
for x in range(0, 26):
    if not ((x in q) <= ((x not in p) or (x in a))):
        a.add(x)
print(len(a))
