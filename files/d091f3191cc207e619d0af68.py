def primer_01():
    from ipaddress import ip_network, ip_address
    count = 0
    net = ip_network('192.168.32.160/255.255.255.240')

    for ip in net:
        ip_bin = bin(int(ip))[2:]
        if ip_bin.count('1') % 2 == 0:
            count += 1
    print(count)

