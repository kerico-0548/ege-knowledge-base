# Источник: ЕГЭ_Инфа_ШПОРА_2026.docx, фрагмент 116
def primer_01():
    otvet = []
    for N in range(0, 1000):
        num = bin(N)[2:]    # перевод в двоичную запись

        if N % 3 == 0:    # условие А
            num += num[-3:]
        else:             # условие Б
            ost = (N % 3) * 3
            num += bin(ost)[2:]

        R = int(num, 2)
        if R > 151:    # перевод в десятичную из двоичной
            otvet.append(R)
    print(min(otvet))     # нахождение мин. числа для ответа

# Источник: ЕГЭ_Инфа_ШПОРА_2026.docx, фрагмент 125
def primer_02():
    def tri(num):
        s = ''
        while num > 0:
            s += str(num % 3)
            num //= 3
        return s[::-1]

    maxi = 0
    for n in range(0, 1000):
        x = tri(n)

        if n % 3 == 0:
            x = '1' + x + '02'
        else:
            x += tri((n % 3) * 4)

        R = int(x, 3)
        if R < 199:
            maxi = max(maxi, n)
    print(maxi)

